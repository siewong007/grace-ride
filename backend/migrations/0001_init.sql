-- 恩典同行 Grace Ride — consolidated schema (PostgreSQL)
-- Single source of truth: exactly ONE migration file. Former 0002–0006
-- (indexes, CHECKs, user_roles, demo_batch FKs, terms index) are folded below.
--
-- Conventions:
--   • Times are local Asia/Kuala_Lumpur ISO strings: YYYY-MM-DD"T"HH24:MI:SS
--   • Money is integer cents (RM 0.01)
--   • Booleans are BIGINT 0/1
--   • Role lists are comma-separated TEXT
--   • demo_batch stamps seed rows so they can be wiped without touching live data
--
-- Applied at API startup via sqlx::migrate!("./migrations") in connect_db().

-- =====================================================================
-- Auth & members
-- =====================================================================

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL,
    email           TEXT NOT NULL UNIQUE,
    verification_token TEXT,
    verification_token_expires TEXT,
    phone           TEXT NOT NULL DEFAULT '',
    photo_file_id   BIGINT,                         -- soft ref to files.id (set after upload)
    roles           TEXT NOT NULL DEFAULT '',       -- admin,transport,finance,leader,driver
    status          TEXT NOT NULL DEFAULT 'active', -- active | disabled
    password_hash   TEXT,
    totp_secret     TEXT,
    totp_enabled    BIGINT NOT NULL DEFAULT 0,
    totp_last_step  BIGINT NOT NULL DEFAULT 0,      -- TOTP replay protection (ex-0002)
    webauthn_uuid   TEXT NOT NULL,
    badges_opt_out  BIGINT NOT NULL DEFAULT 0,
    carpool_enabled BIGINT NOT NULL DEFAULT 0,
    spare_seats     BIGINT NOT NULL DEFAULT 1,
    lang            TEXT NOT NULL DEFAULT 'zh' CHECK (lang IN ('zh','en')),  -- ex-0003
    terms_accepted_at TEXT,                         -- ex-0006; NULL = not yet agreed
    demo_batch      TEXT,                           -- ex-0005
    created_at      TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);
CREATE INDEX idx_demo_batch_users ON users(demo_batch) WHERE demo_batch IS NOT NULL;

CREATE TABLE vehicles (
    user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    model      TEXT NOT NULL,
    color      TEXT NOT NULL,
    plate      TEXT NOT NULL,
    seats      BIGINT NOT NULL DEFAULT 4,
    demo_batch TEXT
);

CREATE TABLE invites (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       TEXT NOT NULL UNIQUE,
    kind        TEXT NOT NULL DEFAULT 'invite',    -- invite | recovery
    email       TEXT NOT NULL,
    name        TEXT NOT NULL DEFAULT '',
    roles       TEXT NOT NULL DEFAULT '',
    group_ids   TEXT NOT NULL DEFAULT '[]',
    user_id     BIGINT REFERENCES users(id),       -- set for recovery invites
    created_by  BIGINT NOT NULL REFERENCES users(id),
    expires_at  TEXT NOT NULL,
    used_at     TEXT,
    demo_batch  TEXT,
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE passkeys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    cred_id     TEXT NOT NULL UNIQUE,
    passkey     TEXT NOT NULL,
    label       TEXT NOT NULL DEFAULT '',
    demo_batch  TEXT,
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    last_used   TEXT
);

CREATE TABLE sessions (
    token       TEXT PRIMARY KEY,                  -- SHA-256 hash of the cookie value
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    mfa_ok      BIGINT NOT NULL DEFAULT 0,
    expires_at  TEXT NOT NULL,
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);
CREATE INDEX idx_sessions_user ON sessions(user_id);
CREATE INDEX idx_sessions_expires ON sessions(expires_at);

CREATE TABLE auth_challenges (
    id          TEXT PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    kind        TEXT NOT NULL,                     -- reg | auth
    state       TEXT NOT NULL,
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
