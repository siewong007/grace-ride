CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL,
    email           TEXT NOT NULL UNIQUE,
    verification_token TEXT,
    verification_token_expires TEXT,
    phone           TEXT NOT NULL DEFAULT '',
    photo_file_id   BIGINT,                         -- soft ref to files.id (set after upload)
    roles           TEXT NOT NULL DEFAULT '',       -- comma-separated role keys
    status          TEXT NOT NULL DEFAULT 'active', -- active | pending | disabled
    password_hash   TEXT,
    totp_secret     TEXT,
    totp_enabled    BIGINT NOT NULL DEFAULT 0,
    totp_last_step  BIGINT NOT NULL DEFAULT 0,
    webauthn_uuid   TEXT NOT NULL,
    badges_opt_out  BIGINT NOT NULL DEFAULT 0,
    carpool_enabled BIGINT NOT NULL DEFAULT 0,
    spare_seats     BIGINT NOT NULL DEFAULT 1,
    lang            TEXT NOT NULL DEFAULT 'zh' CHECK (lang IN ('zh','en')),
    terms_accepted_at TEXT,
    demo_batch      TEXT,
    created_at      TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    readiness_prompt_mins BIGINT NOT NULL DEFAULT 45,
    gate_wait_mins  BIGINT NOT NULL DEFAULT 5,
    totp_backup_codes TEXT,
    auto_lock_mins  BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_users_phone CHECK (
        phone = '' OR (length(trim(phone)) >= 10 AND length(trim(phone)) <= 20)
    ),
    CONSTRAINT chk_users_carpool_enabled CHECK (carpool_enabled IN (0, 1)),
    CONSTRAINT chk_users_spare_seats CHECK (spare_seats >= 1 AND spare_seats <= 8),
    CONSTRAINT chk_users_totp_enabled CHECK (totp_enabled IN (0, 1)),
    CONSTRAINT chk_users_totp_last_step CHECK (totp_last_step >= 0),
    CONSTRAINT chk_users_badges_opt_out CHECK (badges_opt_out IN (0, 1)),
    CONSTRAINT chk_users_demo_batch CHECK (demo_batch IS NULL OR length(demo_batch) <= 32),
    CONSTRAINT fk_users_demo_batch FOREIGN KEY (demo_batch) REFERENCES demo_batches(batch) ON DELETE SET NULL
);

