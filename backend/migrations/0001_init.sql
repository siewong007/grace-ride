-- 恩典同行 Grace Ride schema (PostgreSQL)
-- Times are stored as local (Asia/Kuala_Lumpur) ISO strings "YYYY-MM-DDTHH:MM[:SS]".
-- Money is stored as integer cents (RM 0.01).

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL,
    email           TEXT NOT NULL UNIQUE,
    phone           TEXT NOT NULL DEFAULT '',
    photo_file_id   BIGINT,
    roles           TEXT NOT NULL DEFAULT '',          -- comma list: admin,transport,finance,leader,driver
    status          TEXT NOT NULL DEFAULT 'active',    -- active | disabled
    password_hash   TEXT,
    totp_secret     TEXT,
    totp_enabled    BIGINT NOT NULL DEFAULT 0,
    webauthn_uuid   TEXT NOT NULL,
    badges_opt_out  BIGINT NOT NULL DEFAULT 0,
    carpool_enabled BIGINT NOT NULL DEFAULT 0,
    spare_seats     BIGINT NOT NULL DEFAULT 1,
    created_at      TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE vehicles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    model   TEXT NOT NULL,
    color   TEXT NOT NULL,
    plate   TEXT NOT NULL,
    seats   BIGINT NOT NULL DEFAULT 4
);

CREATE TABLE invites (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       TEXT NOT NULL UNIQUE,
    kind        TEXT NOT NULL DEFAULT 'invite',        -- invite | recovery
    email       TEXT NOT NULL,
    name        TEXT NOT NULL DEFAULT '',
    roles       TEXT NOT NULL DEFAULT '',
    group_ids   TEXT NOT NULL DEFAULT '[]',
    user_id     BIGINT REFERENCES users(id),            -- for recovery
    created_by  BIGINT NOT NULL REFERENCES users(id),
    expires_at  TEXT NOT NULL,
    used_at     TEXT,
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE passkeys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    cred_id     TEXT NOT NULL UNIQUE,
    passkey     TEXT NOT NULL,
    label       TEXT NOT NULL DEFAULT '',
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    last_used   TEXT
);

CREATE TABLE sessions (
    token       TEXT PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    mfa_ok      BIGINT NOT NULL DEFAULT 0,
    expires_at  TEXT NOT NULL,
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE auth_challenges (
    id          TEXT PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    kind        TEXT NOT NULL,      -- reg | auth
    state       TEXT NOT NULL,
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE recovery_requests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       TEXT NOT NULL,
    reason      TEXT NOT NULL DEFAULT '',
    status      TEXT NOT NULL DEFAULT 'pending',    -- pending | approved | rejected
    resolved_by BIGINT REFERENCES users(id),
    created_at  TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE areas (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    TEXT NOT NULL UNIQUE,
    active  BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE driver_areas (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    area_id BIGINT NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, area_id)
);

CREATE TABLE groups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    is_all      BIGINT NOT NULL DEFAULT 0       -- "全体会员": every active member is implicitly in it
);

CREATE TABLE group_members (
    group_id BIGINT NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, user_id)
);

CREATE TABLE files (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT NOT NULL REFERENCES users(id),
    stored_name   TEXT NOT NULL,
    mime          TEXT NOT NULL,
    original_name TEXT NOT NULL DEFAULT '',
    size          BIGINT NOT NULL DEFAULT 0,
    created_at    TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            TEXT NOT NULL,
    kind             TEXT NOT NULL DEFAULT 'other',    -- badminton | bowling | kayak | walk | other
    description      TEXT NOT NULL DEFAULT '',
    starts_at        TEXT NOT NULL,
    location         TEXT NOT NULL DEFAULT '',
    capacity         BIGINT NOT NULL DEFAULT 0,       -- 0 = unlimited
    cost_note        TEXT NOT NULL DEFAULT '',
    signup_deadline  TEXT,
    status           TEXT NOT NULL DEFAULT 'published',-- published | cancelled | finished
    created_by       BIGINT NOT NULL REFERENCES users(id),
    created_at       TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE event_groups (
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, group_id)
);

CREATE TABLE event_signups (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    status       TEXT NOT NULL DEFAULT 'going',    -- going | waitlist | cancelled
    need_ride    BIGINT NOT NULL DEFAULT 0,
    offer_drive  BIGINT NOT NULL DEFAULT 0,
    offer_seats  BIGINT NOT NULL DEFAULT 0,
    attended     BIGINT,                          -- NULL unknown, 0 absent, 1 attended
    created_at   TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    UNIQUE (event_id, user_id)
);

CREATE TABLE rides (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id      BIGINT NOT NULL REFERENCES users(id),
    driver_id         BIGINT REFERENCES users(id),
    event_id          BIGINT REFERENCES events(id),
    pickup_at         TEXT NOT NULL,
    pickup_area_id    BIGINT NOT NULL REFERENCES areas(id),
    pickup_address    TEXT NOT NULL DEFAULT '',     -- private until approved
    destination       TEXT NOT NULL DEFAULT '',
    seats             BIGINT NOT NULL DEFAULT 1,
    assistance        TEXT NOT NULL DEFAULT '',
    notes             TEXT NOT NULL DEFAULT '',
    status            TEXT NOT NULL DEFAULT 'pending_driver',
    -- pending_driver → pending_passenger → pending_approval → confirmed → in_progress → completed
    -- side states: pending_driver_confirm (after reassignment), cancelled, no_show,
    --              alt_transport (交通组批准 Grab 替代交通)
    trip_id           BIGINT,                      -- rides sharing a driver/time form one trip (shared chat)
    needs_attention   BIGINT NOT NULL DEFAULT 0,
    attention_reason  TEXT NOT NULL DEFAULT '',
    approved_by       BIGINT REFERENCES users(id),
    started_at        TEXT,
    picked_up_at      TEXT,
    completed_at      TEXT,
    created_at        TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    updated_at        TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);
CREATE INDEX idx_rides_status ON rides(status);
CREATE INDEX idx_rides_driver ON rides(driver_id);
CREATE INDEX idx_rides_passenger ON rides(passenger_id);

CREATE TABLE ride_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id    BIGINT NOT NULL,                 -- = rides.trip_id
    user_id    BIGINT REFERENCES users(id),     -- NULL = system message
    body       TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE driver_locations (
    driver_id  BIGINT PRIMARY KEY REFERENCES users(id),
    lat        DOUBLE PRECISION NOT NULL,
    lng        DOUBLE PRECISION NOT NULL,
    heading    DOUBLE PRECISION,
    updated_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title      TEXT NOT NULL,
    body       TEXT NOT NULL DEFAULT '',
    link       TEXT NOT NULL DEFAULT '',
    read_at    TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);
CREATE INDEX idx_notif_user ON notifications(user_id, read_at);

CREATE TABLE announcements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      TEXT NOT NULL,
    body       TEXT NOT NULL,
    pinned     BIGINT NOT NULL DEFAULT 0,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE help_tickets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    ride_id    BIGINT REFERENCES rides(id),
    subject    TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'open',    -- open | answered | closed
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    updated_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE help_replies (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT NOT NULL REFERENCES help_tickets(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    body       TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE audit_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id   BIGINT REFERENCES users(id),
    action     TEXT NOT NULL,
    entity     TEXT NOT NULL,
    entity_id  BIGINT,
    detail     TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE reimbursements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id),
    ride_id         BIGINT REFERENCES rides(id),
    amount_cents    BIGINT NOT NULL,
    description     TEXT NOT NULL DEFAULT '',
    receipt_file_id BIGINT NOT NULL REFERENCES files(id),
    payee_name      TEXT NOT NULL DEFAULT '',
    payee_phone     TEXT NOT NULL DEFAULT '',
    status          TEXT NOT NULL DEFAULT 'pending',  -- pending | returned | rejected | approved | paid
    review_note     TEXT NOT NULL DEFAULT '',
    reviewed_by     BIGINT REFERENCES users(id),
    payee_verified  BIGINT NOT NULL DEFAULT 0,
    paid_ref        TEXT NOT NULL DEFAULT '',
    paid_by         BIGINT REFERENCES users(id),
    paid_at         TEXT,
    created_at      TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    updated_at      TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE settlements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       BIGINT NOT NULL REFERENCES events(id),
    created_by     BIGINT NOT NULL REFERENCES users(id),
    title          TEXT NOT NULL,
    split_mode     TEXT NOT NULL DEFAULT 'equal',   -- equal | custom
    subsidy_cents  BIGINT NOT NULL DEFAULT 0,
    payee_name     TEXT NOT NULL DEFAULT '',
    payee_account  TEXT NOT NULL DEFAULT '',       -- TNG phone / DuitNow / bank details
    due_date       TEXT,
    status         TEXT NOT NULL DEFAULT 'draft',  -- draft | published | closed
    version        BIGINT NOT NULL DEFAULT 1,
    created_at     TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE settlement_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id   BIGINT NOT NULL REFERENCES settlements(id) ON DELETE CASCADE,
    label           TEXT NOT NULL,
    amount_cents    BIGINT NOT NULL,
    receipt_file_id BIGINT REFERENCES files(id)
);

CREATE TABLE settlement_shares (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id  BIGINT NOT NULL REFERENCES settlements(id) ON DELETE CASCADE,
    user_id        BIGINT NOT NULL REFERENCES users(id),
    amount_cents   BIGINT NOT NULL,
    status         TEXT NOT NULL DEFAULT 'unpaid',  -- unpaid | pending | confirmed | needs_info
    proof_file_id  BIGINT REFERENCES files(id),
    txn_ref        TEXT NOT NULL DEFAULT '',
    paid_date      TEXT,
    note           TEXT NOT NULL DEFAULT '',
    updated_at     TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    UNIQUE (settlement_id, user_id)
);

CREATE TABLE settlement_revisions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id  BIGINT NOT NULL REFERENCES settlements(id) ON DELETE CASCADE,
    version        BIGINT NOT NULL,
    snapshot       TEXT NOT NULL,
    reason         TEXT NOT NULL DEFAULT '',
    created_by     BIGINT NOT NULL REFERENCES users(id),
    created_at     TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);
