CREATE TABLE rides (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id      BIGINT NOT NULL REFERENCES users(id),
    driver_id         BIGINT REFERENCES users(id),
    event_id          BIGINT REFERENCES events(id),
    pickup_at         TEXT NOT NULL,
    pickup_area_id    BIGINT NOT NULL REFERENCES areas(id),
    pickup_address    TEXT NOT NULL DEFAULT '',    -- private until approved
    destination       TEXT NOT NULL DEFAULT '',
    seats             BIGINT NOT NULL DEFAULT 1,
    assistance        TEXT NOT NULL DEFAULT '',
    notes             TEXT NOT NULL DEFAULT '',
    status            TEXT NOT NULL DEFAULT 'pending_driver',
    -- pending_driver → pending_passenger → pending_approval → confirmed → in_progress → completed
    -- side: pending_driver_confirm | cancelled | no_show | alt_transport
    trip_id           BIGINT,                      -- shared chat key
    needs_attention   BIGINT NOT NULL DEFAULT 0,
    attention_reason  TEXT NOT NULL DEFAULT '',
    approved_by       BIGINT REFERENCES users(id),
    started_at        TEXT,
    picked_up_at      TEXT,
    completed_at      TEXT,
    reminder_sent     BIGINT NOT NULL DEFAULT 0,   -- ex-0002
    demo_batch        TEXT,
    created_at        TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    updated_at        TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);
CREATE INDEX idx_rides_status ON rides(status);
CREATE INDEX idx_rides_driver ON rides(driver_id);
CREATE INDEX idx_rides_passenger ON rides(passenger_id);
CREATE INDEX idx_rides_pickup ON rides(pickup_at);
CREATE INDEX idx_rides_trip ON rides(trip_id);
CREATE INDEX idx_demo_batch_rides ON rides(demo_batch) WHERE demo_batch IS NOT NULL;

