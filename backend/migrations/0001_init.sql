-- =====================================================================
-- Rides, trips & live location
-- =====================================================================

-- A trip is the group of confirmed rides one driver takes to one place together; its
-- id is the id of the ride that started it (routes::rides::assign_trip). The app sets
-- rides.trip_id directly and a trigger adds the trips row first. Deleting a trip
-- removes its chat and unlinks its rides.
CREATE TABLE IF NOT EXISTS trips (
    id         BIGINT PRIMARY KEY,
    created_at TEXT NOT NULL DEFAULT (app_now())
);

CREATE TABLE IF NOT EXISTS rides (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id      BIGINT NOT NULL REFERENCES users(id),
    driver_id         BIGINT REFERENCES users(id),
    event_id          BIGINT REFERENCES events(id),
    pickup_at         TEXT NOT NULL,
    pickup_area_id    BIGINT NOT NULL REFERENCES areas(id),
    pickup_address    TEXT NOT NULL DEFAULT '',
    destination       TEXT NOT NULL DEFAULT '',
    seats             BIGINT NOT NULL DEFAULT 1,
    assistance        TEXT NOT NULL DEFAULT '',
    notes             TEXT NOT NULL DEFAULT '',
    status            TEXT NOT NULL DEFAULT 'pending_driver',
    -- pending_driver → pending_passenger → pending_approval → confirmed → in_progress → completed
    -- side: pending_driver_confirm | cancelled | no_show | alt_transport
    trip_id           BIGINT,
    needs_attention   BIGINT NOT NULL DEFAULT 0,
    attention_reason  TEXT NOT NULL DEFAULT '',
    approved_by       BIGINT REFERENCES users(id),
    started_at        TEXT,
    picked_up_at      TEXT,
    completed_at      TEXT,
    reminder_sent     BIGINT NOT NULL DEFAULT 0,
    demo_batch        TEXT,
    created_at        TEXT NOT NULL DEFAULT (app_now()),
    updated_at        TEXT NOT NULL DEFAULT (app_now()),
    distance_km       BIGINT,
    reimbursement_amount_cents BIGINT NOT NULL DEFAULT 0,
    readiness_status  TEXT NOT NULL DEFAULT 'unconfirmed'
        CHECK (readiness_status IN ('unconfirmed', 'ready', 'delayed_5m', 'delayed_10m', 'unable_to_join')),
    readiness_updated_at TEXT,
    delay_minutes     BIGINT NOT NULL DEFAULT 0,
    arrived_at_gate_at TEXT,
    is_proxy          BIGINT NOT NULL DEFAULT 0,
    rider_name        TEXT NOT NULL DEFAULT '',
    rider_phone       TEXT NOT NULL DEFAULT '',
    rider_relationship TEXT NOT NULL DEFAULT '',
    -- Copied from the signup when the ride is made, so reports keep the group someone came as.
    as_group_id       BIGINT REFERENCES groups(id) ON DELETE SET NULL,
    CONSTRAINT chk_rides_status CHECK (status IN (
        'pending_driver','pending_passenger','pending_approval','pending_driver_confirm',
        'confirmed','in_progress','completed','cancelled','no_show','alt_transport'
    )),
    CONSTRAINT chk_rides_seats CHECK (seats >= 1 AND seats <= 15),
    CONSTRAINT chk_rides_assistance CHECK (
        assistance IN ('', 'wheelchair', 'stroller', 'oxygen', 'other')
    ),
    CONSTRAINT fk_rides_demo_batch FOREIGN KEY (demo_batch) REFERENCES demo_batches(batch) ON DELETE SET NULL
);

