CREATE TABLE settlements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       BIGINT NOT NULL REFERENCES events(id),
    created_by     BIGINT NOT NULL REFERENCES users(id),
    title          TEXT NOT NULL,
    split_mode     TEXT NOT NULL DEFAULT 'equal',  -- equal | custom
    subsidy_cents  BIGINT NOT NULL DEFAULT 0,
    payee_name     TEXT NOT NULL DEFAULT '',
    payee_account  TEXT NOT NULL DEFAULT '',      -- TNG / DuitNow / bank
    due_date       TEXT,
    status         TEXT NOT NULL DEFAULT 'draft', -- draft | published | closed
    version        BIGINT NOT NULL DEFAULT 1,
    demo_batch     TEXT,
    created_at     TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    -- Drift fix: seed + expected parity with rides/help_tickets/reimbursements
