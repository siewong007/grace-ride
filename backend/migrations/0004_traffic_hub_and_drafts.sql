-- Multi-version event plan drafts with single-editor lease locks & draft visitors,
-- single-ride change drafts, and per-ride reimbursement exclusion flag.

-- 1. Upgrade event_plan_drafts to support multiple draft versions per event,
--    single-editor lease locks, and draft visitor entries.
ALTER TABLE event_plan_drafts ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;

DO $$
DECLARE
    pk_name text;
    pk_cols text[];
BEGIN
    SELECT c.conname, array_agg(a.attname::text ORDER BY u.ord)
    INTO pk_name, pk_cols
    FROM pg_constraint c
    CROSS JOIN LATERAL unnest(c.conkey) WITH ORDINALITY AS u(attnum, ord)
    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = u.attnum
    WHERE c.conrelid = 'event_plan_drafts'::regclass
      AND c.contype = 'p'
    GROUP BY c.conname;

    IF pk_name IS NOT NULL AND pk_cols IS DISTINCT FROM ARRAY['id'] THEN
        EXECUTE format('ALTER TABLE event_plan_drafts DROP CONSTRAINT %I', pk_name);
        pk_name := NULL;
    END IF;

    IF pk_name IS NULL THEN
        ALTER TABLE event_plan_drafts ADD PRIMARY KEY (id);
    END IF;
END $$;

ALTER TABLE event_plan_drafts ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 1;
ALTER TABLE event_plan_drafts ADD COLUMN IF NOT EXISTS label TEXT NOT NULL DEFAULT '';
ALTER TABLE event_plan_drafts ADD COLUMN IF NOT EXISTS visitors TEXT NOT NULL DEFAULT '[]';
ALTER TABLE event_plan_drafts ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE event_plan_drafts ADD COLUMN IF NOT EXISTS locked_by BIGINT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE event_plan_drafts ADD COLUMN IF NOT EXISTS locked_at TEXT;
ALTER TABLE event_plan_drafts ADD COLUMN IF NOT EXISTS lock_expires_at TEXT;

UPDATE event_plan_drafts SET created_by = updated_by WHERE created_by IS NULL;

DO $$
DECLARE c record;
BEGIN
    FOR c IN
        SELECT conname FROM pg_constraint
        WHERE conrelid = 'event_plan_drafts'::regclass AND contype = 'c'
          AND pg_get_constraintdef(oid) LIKE '%status%'
    LOOP
        EXECUTE format('ALTER TABLE event_plan_drafts DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;

ALTER TABLE event_plan_drafts ADD CONSTRAINT chk_event_plan_drafts_status
    CHECK (status IN ('draft', 'pending_approval', 'approved', 'returned', 'superseded'));

CREATE UNIQUE INDEX IF NOT EXISTS idx_event_plan_drafts_event_version
    ON event_plan_drafts(event_id, version);
CREATE INDEX IF NOT EXISTS idx_event_plan_drafts_event_status
    ON event_plan_drafts(event_id, status);

-- 2. Per-ride reimbursement exclusion flag (0 = normal fixed-rate eligible, 1 = excluded)
ALTER TABLE rides ADD COLUMN IF NOT EXISTS reimbursement_excluded BIGINT NOT NULL DEFAULT 0;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'rides'::regclass AND conname = 'chk_rides_reimbursement_excluded'
    ) THEN
        ALTER TABLE rides ADD CONSTRAINT chk_rides_reimbursement_excluded
            CHECK (reimbursement_excluded IN (0, 1));
    END IF;
END $$;

-- 3. Single-ride change drafts (shared across traffic group, single-editor lease lock, lead-approved)
CREATE TABLE IF NOT EXISTS ride_change_drafts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ride_id                 BIGINT NOT NULL REFERENCES rides(id) ON DELETE CASCADE,
    version                 BIGINT NOT NULL DEFAULT 1,
    action                  TEXT NOT NULL CHECK (action IN ('approve', 'reassign', 'return', 'alt_transport', 'reimbursement_excluded')),
    driver_id               BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reason                  TEXT NOT NULL DEFAULT '',
    reimbursement_excluded  BIGINT CHECK (reimbursement_excluded IS NULL OR reimbursement_excluded IN (0, 1)),
    status                  TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'pending_approval', 'approved', 'returned', 'superseded')),
    created_by              BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    updated_by              BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    locked_by               BIGINT REFERENCES users(id) ON DELETE SET NULL,
    locked_at               TEXT,
    lock_expires_at         TEXT,
    submitted_by            BIGINT REFERENCES users(id) ON DELETE SET NULL,
    submitted_at            TEXT,
    reviewed_by             BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at             TEXT,
    review_notes            TEXT NOT NULL DEFAULT '',
    created_at              TEXT NOT NULL DEFAULT (app_now()),
    updated_at              TEXT NOT NULL DEFAULT (app_now())
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_ride_change_drafts_ride_version
    ON ride_change_drafts(ride_id, version);
CREATE INDEX IF NOT EXISTS idx_ride_change_drafts_status
    ON ride_change_drafts(status);
