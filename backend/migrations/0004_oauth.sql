-- 0004 · Third-party (OAuth) account linking.
-- Grace Ride stays invite-only: Google sign-in links to an existing invite
-- (email match) or existing user; it never self-registers a new member.
CREATE TABLE oauth_states (
    state      TEXT PRIMARY KEY,
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE TABLE oauth_accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider        TEXT NOT NULL DEFAULT 'google',   -- google
    provider_user_id TEXT NOT NULL,                    -- Google sub
    email           TEXT NOT NULL,                    -- verified email from provider
    created_at      TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    UNIQUE (provider, provider_user_id)
);
CREATE INDEX idx_oauth_accounts_user ON oauth_accounts(user_id);
CREATE INDEX idx_oauth_accounts_email ON oauth_accounts(email);
