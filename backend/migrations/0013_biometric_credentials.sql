-- Hardware-backed device biometric public keys (ECDSA P-256) for native mobile sign-in & re-auth.
CREATE TABLE IF NOT EXISTS biometric_credentials (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    cred_id     TEXT NOT NULL UNIQUE,
    public_key  BYTEA NOT NULL,
    label       TEXT NOT NULL DEFAULT '',
    created_at  TEXT NOT NULL DEFAULT (app_now()),
    last_used   TEXT,
    updated_at  TEXT NOT NULL DEFAULT (app_now()),
    CONSTRAINT chk_biometric_cred_id CHECK (length(trim(cred_id)) >= 16 AND length(trim(cred_id)) <= 128),
    CONSTRAINT chk_biometric_pubkey_len CHECK (octet_length(public_key) = 65),
    CONSTRAINT chk_biometric_label CHECK (char_length(label) <= 60)
);

CREATE INDEX IF NOT EXISTS idx_biometric_credentials_user_id ON biometric_credentials(user_id);

ALTER TABLE auth_challenges DROP CONSTRAINT IF EXISTS chk_auth_challenges_kind;
ALTER TABLE auth_challenges ADD CONSTRAINT chk_auth_challenges_kind
    CHECK (kind IN ('reg', 'auth', 'bio_reg', 'bio_login', 'bio_reauth'));
