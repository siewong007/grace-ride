-- Notification module enhancements (Phases 1–4):
-- 1. Decoupled driver ride reminders (`driver_reminder_sent` + trigger update).
-- 2. Structured notification metadata (`category`, `event_type`, `priority`, `entity_type`, `entity_id`).
-- 3. Web Push device metadata (`last_delivered_at`, `device_label`).
-- 4. Durable external delivery outbox (`notification_deliveries`).
-- 5. Per-user notification preferences (`user_notification_prefs`).
-- 6. One-tap Telegram pairing tokens (`telegram_link_tokens`).
-- 7. Native mobile push tokens (`mobile_push_tokens`).
-- Safe to replay over existing databases.

-- 1. Decoupled driver ride reminders
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'rides'
          AND column_name = 'driver_reminder_sent'
    ) THEN
        ALTER TABLE rides ADD COLUMN driver_reminder_sent BIGINT NOT NULL DEFAULT 0;
        UPDATE rides SET driver_reminder_sent = 1 WHERE reminder_sent = 1;
    END IF;
END
$$;

ALTER TABLE rides DROP CONSTRAINT IF EXISTS chk_rides_driver_reminder_sent;
ALTER TABLE rides ADD CONSTRAINT chk_rides_driver_reminder_sent
    CHECK (driver_reminder_sent IN (0, 1));

CREATE OR REPLACE FUNCTION rides_rearm_reminder() RETURNS trigger
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
BEGIN
    IF NEW.driver_id IS DISTINCT FROM OLD.driver_id THEN
        NEW.reminder_sent := 0;
        NEW.driver_reminder_sent := 0;
    END IF;
    RETURN NEW;
END
$$;

-- 2. Structured notification metadata
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS category TEXT NOT NULL DEFAULT 'general';
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS event_type TEXT NOT NULL DEFAULT '';
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS priority TEXT NOT NULL DEFAULT 'normal';
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS entity_type TEXT NOT NULL DEFAULT '';
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS entity_id BIGINT;

ALTER TABLE notifications DROP CONSTRAINT IF EXISTS chk_notifications_priority;
ALTER TABLE notifications ADD CONSTRAINT chk_notifications_priority
    CHECK (priority IN ('urgent', 'normal', 'low'));

ALTER TABLE notifications DROP CONSTRAINT IF EXISTS chk_notifications_category;
ALTER TABLE notifications ADD CONSTRAINT chk_notifications_category
    CHECK (category IN ('ride', 'event', 'cost', 'help', 'announcement', 'family', 'admin', 'chat', 'general'));

CREATE INDEX IF NOT EXISTS idx_notifications_user_cat
    ON notifications(user_id, category, id DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_unread_keyset
    ON notifications(user_id, id DESC) WHERE read_at IS NULL;

-- 3. Web Push subscription metadata
ALTER TABLE push_subscriptions ADD COLUMN IF NOT EXISTS last_delivered_at TEXT;
ALTER TABLE push_subscriptions ADD COLUMN IF NOT EXISTS device_label TEXT NOT NULL DEFAULT '';

-- 4. Durable external delivery outbox
CREATE TABLE IF NOT EXISTS notification_deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT REFERENCES notifications(id) ON DELETE SET NULL,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    channel         TEXT NOT NULL,
    target_id       BIGINT,
    target_ref      TEXT NOT NULL DEFAULT '',
    title           TEXT NOT NULL,
    body            TEXT NOT NULL DEFAULT '',
    link            TEXT NOT NULL DEFAULT '',
    category        TEXT NOT NULL DEFAULT 'general',
    priority        TEXT NOT NULL DEFAULT 'normal',
    tag             TEXT NOT NULL DEFAULT '',
    badge_count     BIGINT,
    status          TEXT NOT NULL DEFAULT 'pending',
    attempts        BIGINT NOT NULL DEFAULT 0,
    next_attempt_at TEXT NOT NULL DEFAULT (app_now()),
    last_error      TEXT NOT NULL DEFAULT '',
    created_at      TEXT NOT NULL DEFAULT (app_now()),
    delivered_at    TEXT
);

ALTER TABLE notification_deliveries DROP CONSTRAINT IF EXISTS chk_notif_deliveries_channel;
ALTER TABLE notification_deliveries ADD CONSTRAINT chk_notif_deliveries_channel
    CHECK (channel IN ('web_push', 'telegram', 'whatsapp_webhook', 'mobile_push'));

ALTER TABLE notification_deliveries DROP CONSTRAINT IF EXISTS chk_notif_deliveries_status;
ALTER TABLE notification_deliveries ADD CONSTRAINT chk_notif_deliveries_status
    CHECK (status IN ('pending', 'retry', 'delivered', 'failed', 'gone'));

ALTER TABLE notification_deliveries DROP CONSTRAINT IF EXISTS chk_notif_deliveries_priority;
ALTER TABLE notification_deliveries ADD CONSTRAINT chk_notif_deliveries_priority
    CHECK (priority IN ('urgent', 'normal', 'low'));

CREATE INDEX IF NOT EXISTS idx_notif_deliveries_due
    ON notification_deliveries(next_attempt_at, id) WHERE status IN ('pending', 'retry');
CREATE INDEX IF NOT EXISTS idx_notif_deliveries_created
    ON notification_deliveries(created_at);
CREATE INDEX IF NOT EXISTS idx_notif_deliveries_user_tag
    ON notification_deliveries(user_id, tag, created_at DESC) WHERE tag <> '';

-- 5. User notification preferences
CREATE TABLE IF NOT EXISTS user_notification_prefs (
    user_id            BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    muted_categories   TEXT NOT NULL DEFAULT '[]',
    quiet_hours_start  TEXT NOT NULL DEFAULT '',
    quiet_hours_end    TEXT NOT NULL DEFAULT '',
    hide_lock_details  BIGINT NOT NULL DEFAULT 0,
    driver_remind_mins BIGINT NOT NULL DEFAULT 60,
    telegram_blocked   BIGINT NOT NULL DEFAULT 0,
    updated_at         TEXT NOT NULL DEFAULT (app_now())
);

ALTER TABLE user_notification_prefs DROP CONSTRAINT IF EXISTS chk_user_notif_prefs_hide_lock;
ALTER TABLE user_notification_prefs ADD CONSTRAINT chk_user_notif_prefs_hide_lock
    CHECK (hide_lock_details IN (0, 1));

ALTER TABLE user_notification_prefs DROP CONSTRAINT IF EXISTS chk_user_notif_prefs_tg_blocked;
ALTER TABLE user_notification_prefs ADD CONSTRAINT chk_user_notif_prefs_tg_blocked
    CHECK (telegram_blocked IN (0, 1));

ALTER TABLE user_notification_prefs DROP CONSTRAINT IF EXISTS chk_user_notif_prefs_driver_mins;
ALTER TABLE user_notification_prefs ADD CONSTRAINT chk_user_notif_prefs_driver_mins
    CHECK (driver_remind_mins BETWEEN 15 AND 180);

-- 6. One-tap Telegram pairing tokens
CREATE TABLE IF NOT EXISTS telegram_link_tokens (
    token_hash TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (app_now())
);

CREATE INDEX IF NOT EXISTS idx_tg_link_tokens_user ON telegram_link_tokens(user_id);

-- 7. Native mobile push tokens
CREATE TABLE IF NOT EXISTS mobile_push_tokens (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    platform          TEXT NOT NULL,
    provider          TEXT NOT NULL DEFAULT 'fcm',
    token             TEXT NOT NULL UNIQUE,
    device_label      TEXT NOT NULL DEFAULT '',
    last_delivered_at TEXT,
    created_at        TEXT NOT NULL DEFAULT (app_now())
);

ALTER TABLE mobile_push_tokens DROP CONSTRAINT IF EXISTS chk_mobile_push_platform;
ALTER TABLE mobile_push_tokens ADD CONSTRAINT chk_mobile_push_platform
    CHECK (platform IN ('android', 'ios'));

ALTER TABLE mobile_push_tokens DROP CONSTRAINT IF EXISTS chk_mobile_push_provider;
ALTER TABLE mobile_push_tokens ADD CONSTRAINT chk_mobile_push_provider
    CHECK (provider IN ('fcm', 'unifiedpush'));

CREATE INDEX IF NOT EXISTS idx_mobile_push_user ON mobile_push_tokens(user_id);
