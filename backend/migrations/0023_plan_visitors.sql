-- Visitors recorded on an event's transport plan by traffic staff and cell leaders.
-- Record-keeping only: a visitor here has no account, no link, and gets no messages.
-- Numbered 0023 so it never collides with 0022 (default service areas), whichever
-- of the two ships first. Additive only.
CREATE TABLE IF NOT EXISTS plan_visitors (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    name           TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
    phone          TEXT NOT NULL DEFAULT '',
    notes          TEXT NOT NULL DEFAULT '',
    area_id        BIGINT REFERENCES areas(id) ON DELETE SET NULL,
    pickup_address TEXT NOT NULL DEFAULT '',
    seats          BIGINT NOT NULL DEFAULT 1 CHECK (seats BETWEEN 1 AND 8),
    leg            TEXT NOT NULL DEFAULT 'outbound' CHECK (leg IN ('outbound', 'return')),
    -- The car the visitor rides in, for the record. The driver is not notified.
    driver_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
    -- Who recorded it; they (or a traffic lead) may edit or remove it.
    created_by     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at     TEXT NOT NULL DEFAULT (app_now()),
    updated_at     TEXT NOT NULL DEFAULT (app_now()),
    demo_batch     TEXT
);
CREATE INDEX IF NOT EXISTS idx_plan_visitors_event ON plan_visitors(event_id);
CREATE INDEX IF NOT EXISTS idx_plan_visitors_driver ON plan_visitors(driver_id);
