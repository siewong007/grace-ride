-- 0003 · Normalize roles and group management
-- =====================================================================
--
-- This migration addresses the comma-separated roles TEXT column issue
-- by creating a proper normalized roles table.
--
-- Before: roles TEXT NOT NULL DEFAULT '' (comma-separated: admin,transport,finance,leader,driver)
-- After: separate user_roles table with proper many-to-many relationship
--
-- =====================================================================

-- Step 1: Create the user_roles normalization table
CREATE TABLE user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    UNIQUE (user_id, role)
);

-- Step 2: Populate user_roles from the comma-separated roles in users table
-- Split the comma-separated roles and insert each as a separate row
-- This SQL pattern works for PostgreSQL:
INSERT INTO user_roles (user_id, role, created_at)
SELECT
    id,
    unnest(string_to_array(roles, ',')),
    created_at
FROM users
WHERE roles != '';  -- Only process users with at least one role

-- Step 3: Add NOT NULL constraint with default to users.role column
-- (keep backward compatibility during transition)
ALTER TABLE users ALTER COLUMN roles SET DEFAULT 'driver';

-- Step 4: Add check constraint to ensure valid role names
ALTER TABLE user_roles ADD CONSTRAINT chk_user_roles_role CHECK (
    role IN ('admin','transport','finance','leader','driver')
);

-- Step 5: Create indexes for the new user_roles table
CREATE INDEX IF NOT EXISTS idx_user_roles_user ON user_roles(user_id);
CREATE INDEX IF NOT EXISTS idx_user_roles_role ON user_roles(role);

-- Step 6: Normalize group_ids similarly - create group_user join table
-- Before: group_ids TEXT NOT NULL DEFAULT '[]' (comma-separated)
-- After: separate group_members table (if not already existing)
--
-- Note: group_members table already exists from the init schema,
-- but we'll ensure it's properly populated and add a composite index

-- Create index on group_members if not already exists (it should from init)
CREATE INDEX IF NOT EXISTS idx_group_members_user ON group_members(user_id);
CREATE INDEX IF NOT EXISTS idx_group_members_group ON group_members(group_id);

