-- 5. Standing / recurring ride & driver schedules
CREATE TABLE IF NOT EXISTS recurring_ride_schedules (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind                TEXT NOT NULL CHECK (kind IN ('passenger', 'driver')),
    label               TEXT NOT NULL DEFAULT '',
    weekday             BIGINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    pickup_time         TEXT NOT NULL CHECK (pickup_time ~ '^\d{2}:\d{2}$'),
    area_id             BIGINT NOT NULL REFERENCES areas(id),
    pickup_address      TEXT NOT NULL DEFAULT '',
    destination         TEXT NOT NULL DEFAULT '',
    seats               BIGINT NOT NULL DEFAULT 1 CHECK (seats BETWEEN 1 AND 8),
    assistance          TEXT NOT NULL DEFAULT '',
    notes               TEXT NOT NULL DEFAULT '',
    lead_days           BIGINT NOT NULL DEFAULT 3 CHECK (lead_days BETWEEN 1 AND 14),
    active              BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    last_generated_date TEXT,
    created_at          TEXT NOT NULL DEFAULT (app_now()),
    updated_at          TEXT NOT NULL DEFAULT (app_now())
);
CREATE INDEX IF NOT EXISTS idx_recurring_schedules_user ON recurring_ride_schedules(user_id);

-- 6. Web Push subscriptions & Telegram / WhatsApp alert preferences
CREATE TABLE IF NOT EXISTS push_subscriptions (
