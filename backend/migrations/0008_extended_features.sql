-- Extended features: server-enforced session lock, round-trip ride pairing,
-- saved places & proxy rider defaults, vehicle accessibility flags, standing/recurring
-- ride & driver schedules, Web Push / bot alert preferences, caregiver safe-arrival
-- links, event recurring series & member check-in passes, live calendar feeds,
-- DuitNow QR on settlements, and monthly reimbursement payout batches.
--
-- Fully repeatable for schema replay and upgrade safety.

-- 1. Server-enforced session lock
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS locked_at TEXT;
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS last_seen_at TEXT NOT NULL DEFAULT (app_now());

-- 2. Round-trip / return-leg ride pairing
ALTER TABLE rides ADD COLUMN IF NOT EXISTS leg TEXT NOT NULL DEFAULT 'outbound';
ALTER TABLE rides ADD COLUMN IF NOT EXISTS paired_ride_id BIGINT REFERENCES rides(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_rides_paired ON rides(paired_ride_id) WHERE paired_ride_id IS NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'rides'::regclass AND conname = 'chk_rides_leg') THEN
        ALTER TABLE rides ADD CONSTRAINT chk_rides_leg CHECK (leg IN ('outbound', 'return')) NOT VALID;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'rides'::regclass AND conname = 'chk_rides_leg' AND NOT convalidated) THEN
        ALTER TABLE rides VALIDATE CONSTRAINT chk_rides_leg;
    END IF;
END
$$;

-- 3. Saved places & extended proxy rider defaults / caregiver observer
CREATE TABLE IF NOT EXISTS saved_places (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    label      TEXT NOT NULL,
    area_id    BIGINT REFERENCES areas(id) ON DELETE SET NULL,
    address    TEXT NOT NULL,
    gate_notes TEXT NOT NULL DEFAULT '',
    lat        DOUBLE PRECISION,
    lng        DOUBLE PRECISION,
    is_default BIGINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
    created_at TEXT NOT NULL DEFAULT (app_now()),
    updated_at TEXT NOT NULL DEFAULT (app_now())
);
CREATE INDEX IF NOT EXISTS idx_saved_places_user ON saved_places(user_id);

ALTER TABLE proxy_riders ADD COLUMN IF NOT EXISTS area_id BIGINT REFERENCES areas(id) ON DELETE SET NULL;
ALTER TABLE proxy_riders ADD COLUMN IF NOT EXISTS pickup_address TEXT NOT NULL DEFAULT '';
ALTER TABLE proxy_riders ADD COLUMN IF NOT EXISTS gate_notes TEXT NOT NULL DEFAULT '';
ALTER TABLE proxy_riders ADD COLUMN IF NOT EXISTS caregiver_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS caregiver_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL;

