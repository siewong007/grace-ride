-- 7. Caregiver "Safe Arrival" scoped links
CREATE TABLE IF NOT EXISTS caregiver_passes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  TEXT NOT NULL UNIQUE,
    ride_id     BIGINT NOT NULL REFERENCES rides(id) ON DELETE CASCADE,
    created_by  BIGINT NOT NULL REFERENCES users(id),
    label       TEXT NOT NULL DEFAULT '',
    valid_until TEXT NOT NULL,
    closed_at   TEXT,
    created_at  TEXT NOT NULL DEFAULT (app_now())
);
CREATE INDEX IF NOT EXISTS idx_caregiver_passes_ride ON caregiver_passes(ride_id);

-- 8. Recurring event series & member personal check-in pass code
ALTER TABLE events ADD COLUMN IF NOT EXISTS series_id TEXT;
ALTER TABLE event_signups ADD COLUMN IF NOT EXISTS pass_code TEXT;

UPDATE event_signups
   SET pass_code = substr(md5(random()::text || id::text), 1, 10)
 WHERE pass_code IS NULL;

-- 9. Live calendar subscription token hash
ALTER TABLE users ADD COLUMN IF NOT EXISTS calendar_token_hash TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_calendar_token_hash ON users(calendar_token_hash) WHERE calendar_token_hash IS NOT NULL;

-- 10. DuitNow QR on settlements & monthly reimbursement payout batches
ALTER TABLE settlements ADD COLUMN IF NOT EXISTS payee_qr_file_id BIGINT REFERENCES files(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS payout_batches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month       TEXT NOT NULL,
    title       TEXT NOT NULL,
    total_cents BIGINT NOT NULL DEFAULT 0,
    claim_count BIGINT NOT NULL DEFAULT 0,
    status      TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'paid')),
    paid_ref    TEXT NOT NULL DEFAULT '',
    created_by  BIGINT NOT NULL REFERENCES users(id),
    paid_by     BIGINT REFERENCES users(id),
    paid_at     TEXT,
    created_at  TEXT NOT NULL DEFAULT (app_now())
);

ALTER TABLE reimbursements ADD COLUMN IF NOT EXISTS batch_id BIGINT REFERENCES payout_batches(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_reimbursements_batch ON reimbursements(batch_id) WHERE batch_id IS NOT NULL;
