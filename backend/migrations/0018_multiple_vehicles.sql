-- Allow volunteer drivers to configure multiple vehicles and choose which one is active.

ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS is_active BIGINT NOT NULL DEFAULT 1;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint 
        WHERE conrelid = 'vehicles'::regclass AND conname = 'chk_vehicles_is_active'
    ) THEN
        ALTER TABLE vehicles ADD CONSTRAINT chk_vehicles_is_active CHECK (is_active IN (0, 1));
    END IF;
END $$;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'vehicles'::regclass AND conname = 'chk_vehicle_seats'
    ) THEN
        ALTER TABLE vehicles DROP CONSTRAINT chk_vehicle_seats;
        ALTER TABLE vehicles ADD CONSTRAINT chk_vehicle_seats CHECK (seats >= 1 AND seats <= 9);
    END IF;
END $$;

ALTER TABLE vehicles DROP CONSTRAINT IF EXISTS vehicles_pkey;
ALTER TABLE vehicles ADD CONSTRAINT vehicles_pkey PRIMARY KEY (id);

ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS created_at TEXT NOT NULL DEFAULT (app_now());
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS updated_at TEXT NOT NULL DEFAULT (app_now());

CREATE UNIQUE INDEX IF NOT EXISTS idx_vehicles_user_active ON vehicles (user_id) WHERE is_active = 1;
CREATE UNIQUE INDEX IF NOT EXISTS idx_vehicles_user_plate ON vehicles (user_id, plate);
CREATE INDEX IF NOT EXISTS idx_vehicles_user_id ON vehicles (user_id);
