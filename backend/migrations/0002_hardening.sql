-- Security hardening & operations (2026-11)

-- Session tokens are now stored as SHA-256 hashes; existing raw-token sessions are invalidated.
DELETE FROM sessions;
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions(expires_at);

-- TOTP replay protection: the last accepted 30-second step.
ALTER TABLE users ADD COLUMN totp_last_step BIGINT NOT NULL DEFAULT 0;

-- Per-account password lockout.
CREATE TABLE login_failures (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      TEXT NOT NULL,
    ip         TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);
CREATE INDEX idx_login_failures_email ON login_failures(email, created_at);

-- Background reminders (接送前提醒 / 活动提醒) and unmatched-ride escalation.
ALTER TABLE rides ADD COLUMN reminder_sent BIGINT NOT NULL DEFAULT 0;
ALTER TABLE events ADD COLUMN reminder_sent BIGINT NOT NULL DEFAULT 0;

-- Query paths used on every page load.
CREATE INDEX IF NOT EXISTS idx_messages_trip ON ride_messages(trip_id, id);
CREATE INDEX IF NOT EXISTS idx_signups_user ON event_signups(user_id);
CREATE INDEX IF NOT EXISTS idx_rides_pickup ON rides(pickup_at);
CREATE INDEX IF NOT EXISTS idx_rides_trip ON rides(trip_id);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_logs(entity, entity_id);
CREATE INDEX IF NOT EXISTS idx_shares_user ON settlement_shares(user_id);
CREATE INDEX IF NOT EXISTS idx_group_members_user ON group_members(user_id);
