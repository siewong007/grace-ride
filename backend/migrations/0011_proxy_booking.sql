-- 恩典同行 Grace Ride — Family & Cell Leader Proxy Booking (家人与组长代订车)
--
-- Adds:
-- - rides columns: is_proxy, rider_name, rider_phone, rider_relationship
-- - proxy_riders table: reusable frequent proxy riders per user

ALTER TABLE rides
    ADD COLUMN IF NOT EXISTS is_proxy BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS rider_name TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS rider_phone TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS rider_relationship TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_rides_is_proxy ON rides(is_proxy) WHERE is_proxy = 1;

CREATE TABLE IF NOT EXISTS proxy_riders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    phone TEXT NOT NULL DEFAULT '',
    relationship TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS')),
    updated_at TEXT NOT NULL DEFAULT (to_char(NOW() AT TIME ZONE 'Asia/Kuala_Lumpur', 'YYYY-MM-DD"T"HH24:MI:SS'))
);

CREATE INDEX IF NOT EXISTS idx_proxy_riders_user ON proxy_riders(user_id);
