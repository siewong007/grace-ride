-- Photos of a pickup area, so passengers can recognise where to wait for their ride.
-- The traffic lead, senior staff and traffic team members add them (admin_area_photos);
-- every active member sees them wherever the pickup area is shown. Numbered 0025 so it
-- never collides with 0024 (a parallel change), whichever ships first. Additive only.
CREATE TABLE IF NOT EXISTS area_photos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id     BIGINT NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
    -- The uploaded image. Removing the photo removes the file as well.
    file_id     BIGINT NOT NULL UNIQUE REFERENCES files(id) ON DELETE CASCADE,
    caption     TEXT NOT NULL DEFAULT '' CHECK (length(caption) <= 120),
    sort_order  BIGINT NOT NULL DEFAULT 0,
    -- Who added it; a team member may change or remove only their own photos.
    created_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at  TEXT NOT NULL DEFAULT (app_now()),
    updated_at  TEXT NOT NULL DEFAULT (app_now()),
    demo_batch  TEXT
);
CREATE INDEX IF NOT EXISTS idx_area_photos_area ON area_photos(area_id, sort_order, id);
