-- Driver mileage reimbursement is now a flat fare per pair of areas (e.g. Cheras ↔ PJ)
-- instead of distance × a per-km rate. One price covers both directions.
-- A pair with no fare yet needs the driver's mileage receipt, confirmed by review.

CREATE TABLE IF NOT EXISTS area_fares (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_a_id    BIGINT NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
    area_b_id    BIGINT NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
    amount_cents BIGINT NOT NULL CHECK (amount_cents >= 0),
    updated_at   TEXT NOT NULL DEFAULT (app_now()),
    -- Stored with the smaller id first so each pair exists once.
    CONSTRAINT chk_area_fares_order CHECK (area_a_id <= area_b_id),
    CONSTRAINT uq_area_fares_pair UNIQUE (area_a_id, area_b_id)
);

-- The area an event is held in: the other end of the fare.
ALTER TABLE events ADD COLUMN IF NOT EXISTS area_id BIGINT REFERENCES areas(id) ON DELETE SET NULL;

-- Set when a ride completed for a claimable event but its area pair has no fare.
ALTER TABLE rides ADD COLUMN IF NOT EXISTS mileage_receipt_needed BIGINT NOT NULL DEFAULT 0;

-- 'grab' (a passenger's alternative transport) or 'mileage' (a driver's receipt for a ride).
ALTER TABLE reimbursements ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'grab'
    CHECK (kind IN ('grab', 'mileage'));

DROP TABLE IF EXISTS reimbursement_rates;
