//! Rides errors. Both languages live next to each other.

use super::pair;
use crate::i18n::{keys::ErrorKey, Lang};

pub fn render(lang: Lang, key: &ErrorKey) -> String {
    match key {
        ErrorKey::PickupTimeRequired => pair(lang, "请填写接送时间", "Please enter a pickup time"),
        ErrorKey::InvalidPickupTime => pair(lang, "请填写正确的接送时间", "Please enter a valid pickup time"),
        ErrorKey::PickupTimeInPast => pair(lang, "接送时间不能早于现在", "Pickup time cannot be in the past"),
        ErrorKey::SeatsRange => pair(lang, "乘车人数需为 1–6 位", "Seats must be between 1 and 6"),
        ErrorKey::AddressAndDestinationRequired => pair(lang, "请填写上车地址及目的地", "Please enter pickup address and destination"),
        ErrorKey::PickupAreaRequired => pair(lang, "请选择接送地区", "Please choose a pickup area"),
        ErrorKey::CannotViewEvent => pair(lang, "您无法查看此活动", "You cannot view this event"),
        ErrorKey::DriverCannotClaimOwnRide => pair(lang, "不能接送自己", "You cannot claim your own ride"),
        ErrorKey::CannotPickOwnRide => pair(lang, "不能选择自己的接送报名", "You cannot pick your own ride request"),
        ErrorKey::FillVehicleDetailsFirst => pair(lang, "请先在司机设置中填写车辆资料", "Please add your vehicle details in driver settings first"),
        ErrorKey::NotEnoughSeatsSlot { load, cap } => match lang {
            Lang::Zh => format!("座位不足：该时段已安排 {load} 位，可提供 {cap} 位。如需多载，请在司机设置开启共乘模式。"),
            Lang::En => format!("Not enough seats: {load} booked in this slot, {cap} available. Enable carpool mode in driver settings to carry more."),
        },
        ErrorKey::RidePickedByAnotherDriver => pair(lang, "此报名已被其他司机选择", "This request has been picked by another driver"),
        ErrorKey::DriverAlreadyClaimed => pair(lang, "此行程已有司机", "This ride has already been claimed"),
        ErrorKey::DriverAlreadyAssigned => pair(lang, "您已挑选此行程", "You have already claimed this ride"),
        ErrorKey::CannotClaimMultipleDrivers => pair(lang, "您目前已有正在进行的接送，不能同时挑选其他行程", "You already have an active ride in progress and cannot claim another"),
        ErrorKey::RideNotAvailableForClaim => pair(lang, "行程已被其他司机挑选或已不在开放状态", "Ride is no longer available to be claimed"),
        ErrorKey::OnlyPassengerCanRespond => pair(lang, "只有乘客本人可以回应", "Only the passenger can respond"),
        ErrorKey::TripAlreadyApproved => pair(lang, "行程已被批准", "This ride has already been approved"),
        ErrorKey::TripNotApproved => pair(lang, "行程尚未批准", "This ride has not been approved yet"),
        ErrorKey::TripAlreadyCancelled => pair(lang, "行程已取消", "This ride has been cancelled"),
        ErrorKey::TripAlreadyCompleted => pair(lang, "行程已完成", "This ride has been completed"),
        ErrorKey::DriverCannotDrive => pair(lang, "司机无法出车", "Driver cannot drive"),
        ErrorKey::StartTripFirst => pair(lang, "请先开始行程", "Start the trip first"),
        ErrorKey::InvalidLocation => pair(lang, "位置无效", "Invalid location"),
        ErrorKey::MaxLiveDriversReached { live, limit } => match lang {
            Lang::Zh => format!("目前已有 {live} 位司机在行程中（上限 {limit}），请稍后或联系交通组。"),
            Lang::En => format!("There are already {live} drivers on trips (limit {limit}); try again later or contact transport staff."),
        },
        ErrorKey::RideStatusChanged => pair(lang, "接送状态已改变，请重新整理", "Ride status has changed, please refresh"),
        ErrorKey::GroupChatClosed => pair(lang, "本趟群聊已关闭", "The group chat for this trip is closed"),
        ErrorKey::GroupChatNotApproved => pair(lang, "行程获批准后才开放群聊", "Group chat opens once the trip is approved"),
        ErrorKey::OnlyTripMembersCanViewChat => pair(lang, "只有本趟成员可以查看群聊", "Only members of this trip can view the chat"),
        ErrorKey::InvalidMessageLength => pair(lang, "讯息长度不正确", "Message length is invalid"),
        ErrorKey::NoDriverYet => pair(lang, "尚未有司机", "No driver yet"),
        ErrorKey::DriverNotFound => pair(lang, "找不到此司机", "Driver not found"),
        ErrorKey::DriverScheduleMismatch => pair(lang, "司机的接送时间与您的需求不相符", "The driver's time does not match your request"),
        ErrorKey::DriverCapacityMismatch => pair(lang, "司机的乘车人数与您的需求不相符", "The driver's vehicle cannot seat your group"),
        ErrorKey::DriverStatusInvalid => pair(lang, "司机状态无效", "Driver status is invalid"),
        ErrorKey::DriverAlreadyOnTrip => pair(lang, "原司机已在行程中", "The driver is already on the trip"),
        ErrorKey::DriverAssignedOtherRide => pair(lang, "该司机已接送其他行程", "This driver is already assigned to another ride"),
        ErrorKey::NotEnoughDriverSeats { load, cap } => match lang {
            Lang::Zh => format!("司机座位不足：已安排 {load} 位，可提供 {cap} 位"),
            Lang::En => format!("Not enough driver seats: {load} booked, {cap} available"),
        },
        ErrorKey::NotEnoughDriverSeatsReassign { load, cap } => match lang {
            Lang::Zh => format!("该司机座位不足：已安排 {load} 位，可提供 {cap} 位"),
            Lang::En => format!("Not enough seats for this driver: {load} booked, {cap} available"),
        },
        ErrorKey::NotRideDriver => pair(lang, "您不是此接送的司机", "You are not the driver of this ride"),
        ErrorKey::NotRidePassenger => pair(lang, "您不是此接送的乘客", "You are not the passenger of this ride"),
        ErrorKey::CannotViewLocation => pair(lang, "您无法查看此位置", "You cannot view this location"),
        ErrorKey::CannotViewRide => pair(lang, "您无法查看此接送", "You cannot view this ride"),
        ErrorKey::TripResponseNotAllowed => pair(lang, "此行程目前不接受回应", "This ride is not accepting responses right now"),
        ErrorKey::OnlyVolunteerDriversCanSet => pair(lang, "只有志愿司机可以设置", "Only volunteer drivers can change settings"),
        ErrorKey::SpareSeatsRange => pair(lang, "空余座位需为 1–7", "Spare seats must be between 1 and 7"),
        ErrorKey::VehicleModelAndPlateRequired => pair(lang, "请填写车型及车牌", "Please enter vehicle model and plate"),
        ErrorKey::VehicleSeatsRange => pair(lang, "车辆座位数需为 2–9", "Vehicle seats must be between 2 and 9"),
        ErrorKey::MemberNotVolunteerDriver => pair(lang, "此会员不是志愿司机", "This member is not a volunteer driver"),
        ErrorKey::DriverCannotBePassenger => pair(lang, "司机不能是乘客本人", "The driver cannot be the passenger themselves"),
        ErrorKey::OnlyPassengerOrStaffCanCancel => pair(lang, "只有乘客或交通组可以取消", "Only the passenger or transport staff can cancel"),
        ErrorKey::OnlyVolunteerDriversCanView => pair(lang, "只有志愿司机可以查看", "Only volunteer drivers can view"),
        ErrorKey::OnlyVolunteerDriversCanChoose => pair(lang, "只有志愿司机可以选择接送", "Only volunteer drivers can choose rides"),
        other => panic!("{} is not a rides error", other.code()),
    }
}
