    /// Human-readable message in the recipient's language.
    pub fn render(&self, lang: Lang) -> String {
        super::locales::render(lang, self)
    }

    /// Values the frontend interpolates into the same message.
    /// Absent for errors whose text does not depend on runtime numbers.
    pub fn params(&self) -> Option<serde_json::Value> {
        match self {
            Self::PasskeyRegistrationFailed(detail) => Some(json!({ "detail": detail })),
            Self::NotEnoughSeatsSlot { load, cap }
            | Self::NotEnoughDriverSeats { load, cap }
            | Self::NotEnoughDriverSeatsReassign { load, cap } => {
                Some(json!({ "load": load, "cap": cap }))
            }
            Self::MaxLiveDriversReached { live, limit } => {
                Some(json!({ "live": live, "limit": limit }))
            }
            Self::SplitMismatch { sum, total, diff } => {
                Some(json!({ "sum": sum, "total": total, "diff": diff }))
            }
            Self::CustomSplitMismatch { sum, total } => Some(json!({ "sum": sum, "total": total })),
            Self::RevisionSplitMismatch {
                sum,
                new_total,
                diff,
            } => Some(json!({ "sum": sum, "new_total": new_total, "diff": diff })),
            Self::UnattendedMembers(count) | Self::OpenPaymentsRemain(count) => {
                Some(json!({ "count": count }))
            }
            _ => None,
        }
    }
