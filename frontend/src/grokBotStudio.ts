const NUM_RE = /-?\d*\.?\d+/g;

export function parseBezier64Coords(d: string): Float32Array {
  const matches = d.match(NUM_RE) ?? [];
  const arr = new Float32Array(matches.length);
  for (let i = 0; i < matches.length; i++) {
    arr[i] = Number(matches[i]);
  }
  return arr;
}

/** Build a 64-segment closed cubic Bezier path sampled clockwise from +X (matching Circle's phase). */
export function buildPolar64Coords(pointAt: (theta: number) => [number, number]): Float32Array {
  const n = 64;
  const pts: [number, number][] = [];
  for (let i = 0; i < n; i++) {
    pts.push(pointAt((i / n) * Math.PI * 2));
  }
  const out = new Float32Array(2 + n * 6);
  out[0] = pts[0][0];
  out[1] = pts[0][1];
  for (let i = 0; i < n; i++) {
    const pPrev = pts[(i - 1 + n) % n];
    const p0 = pts[i];
    const p1 = pts[(i + 1) % n];
    const pNext = pts[(i + 2) % n];
    const c1x = p0[0] + (p1[0] - pPrev[0]) / 6;
    const c1y = p0[1] + (p1[1] - pPrev[1]) / 6;
    const c2x = p1[0] - (pNext[0] - p0[0]) / 6;
    const c2y = p1[1] - (pNext[1] - p0[1]) / 6;
    const base = 2 + i * 6;
    out[base] = c1x;
    out[base + 1] = c1y;
    out[base + 2] = c2x;
    out[base + 3] = c2y;
    out[base + 4] = p1[0];
    out[base + 5] = p1[1];
  }
  return out;
}

export function coordsToBezier64Path(c: Float32Array): string {
  if (c.length < 386) return GROKBOT_SHAPE_PATHS.circle;
  const segs: string[] = [`M${c[0].toFixed(2)} ${c[1].toFixed(2)}`];
  for (let i = 2; i < 386; i += 6) {
    segs.push(
      `C${c[i].toFixed(2)} ${c[i + 1].toFixed(2)} ${c[i + 2].toFixed(2)} ${c[i + 3].toFixed(2)} ${c[i + 4].toFixed(2)} ${c[i + 5].toFixed(2)}`,
    );
  }
  segs.push('Z');
  return segs.join('');
}

