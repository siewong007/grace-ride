export interface GrokBotSpec {
  shape: GrokBotShape;
  face: GrokBotFace;
  color: GrokBotColor;
}

export const DEFAULT_GROKBOT_SPEC: GrokBotSpec = {
  shape: 'circle',
  face: 'neutral',
  color: 'blue',
};

export const isGrokBotShape = (v?: string | null): v is GrokBotShape =>
  !!v && (GROKBOT_SHAPES as readonly string[]).includes(v);

export const isGrokBotFace = (v?: string | null): v is GrokBotFace =>
  !!v && (GROKBOT_FACES as readonly string[]).includes(v);

export const isGrokBotColor = (v?: string | null): v is GrokBotColor =>
  !!v && (GROKBOT_COLORS as readonly string[]).includes(v);

export const isGrokBotMove = (v?: string | null): v is GrokBotMove =>
  !!v && (GROKBOT_MOVES as readonly string[]).includes(v);

export const isGrokBotIcon = (raw?: string | null): boolean =>
  raw === 'grokbot' || (typeof raw === 'string' && raw.startsWith('grokbot:'));

export function parseGrokBotIcon(raw?: string | null): GrokBotSpec | null {
  if (!raw) return null;
  const trimmed = raw.trim();
  if (trimmed === 'grokbot') return { ...DEFAULT_GROKBOT_SPEC };
  if (!trimmed.startsWith('grokbot:')) return null;
  const parts = trimmed.split(':');
  if (parts.length !== 4) return null;
  const [, sh, face, col] = parts;
  if (!isGrokBotShape(sh) || !isGrokBotFace(face) || !isGrokBotColor(col)) return null;
  return { shape: sh, face, color: col };
}

export function encodeGrokBotIcon(spec: GrokBotSpec): string {
  return `grokbot:${spec.shape}:${spec.face}:${spec.color}`;
}

export function randomGrokBotSpec(exclude?: GrokBotSpec): GrokBotSpec {
  for (let attempt = 0; attempt < 12; attempt++) {
    const next: GrokBotSpec = {
      shape: GROKBOT_SHAPES[Math.floor(Math.random() * GROKBOT_SHAPES.length)],
      face: GROKBOT_FACES[Math.floor(Math.random() * GROKBOT_FACES.length)],
      color: GROKBOT_COLORS[Math.floor(Math.random() * GROKBOT_COLORS.length)],
    };
    if (
      !exclude ||
      next.shape !== exclude.shape ||
      next.face !== exclude.face ||
      next.color !== exclude.color
    ) {
      return next;
    }
  }
  return { shape: 'squircle', face: 'happy', color: 'purple' };
}

